"""Make the hero portrait: the face as one red spiral line.

Samples the photograph's tone along an Archimedean spiral (the same walk as
spiralPath() in components/personal/spiral.ts) and writes the tones, 4 bits
each, to components/personal/portrait.ts. The page rebuilds the spiral and
draws it as one pen stroke whose thickness is the tone.

    python scripts/spiral-portrait.py public/kumma/portrait.jpg
"""

import base64
import math
import pathlib
import sys

import numpy as np
from PIL import Image, ImageFilter, ImageOps

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "components" / "personal" / "portrait.ts"
TURNS, RADIUS, STEP, GAMMA = 36, 196.0, 1.4, 0.9

im = Image.open(sys.argv[1]).convert("L")
# A square on the face, centred between nose bridge and eyes.
im = im.crop((85, 50, 325, 290)).resize((400, 400), Image.LANCZOS)
im = ImageOps.autocontrast(im, cutoff=1)
blur = im.filter(ImageFilter.GaussianBlur(14))
a = np.asarray(im, float) / 255
b = np.asarray(blur, float) / 255
a = np.clip(a + 0.8 * (a - b), 0, 1)  # local contrast: the features, not the lighting
a = np.asarray(Image.fromarray((a * 255).astype(np.uint8)).filter(ImageFilter.GaussianBlur(1.0)), float) / 255
dark = np.clip((1 - a - 0.04) / 0.96, 0, 1) ** GAMMA
# The outer rings dissolve into paper.
yy, xx = np.mgrid[:400, :400]
rr = np.hypot(xx - 200, yy - 200) / RADIUS
dark *= np.clip((1 - rr) / 0.1, 0, 1)

pitch = RADIUS / TURNS
end = math.pi * 2 * TURNS
tones = []
th = 0.0
while th < end:
    r = pitch * th / (math.pi * 2)
    x, y = 200 + r * math.cos(th), 200 + r * math.sin(th)
    v = dark[min(399, max(0, int(y))), min(399, max(0, int(x)))]
    tones.append(int(round(v * 15)))
    th += STEP / max(r, 2)

packed = bytearray((len(tones) + 1) // 2)
for i, t in enumerate(tones):
    packed[i >> 1] |= t << (4 if i & 1 else 0)
data = base64.b64encode(bytes(packed)).decode()
OUT.write_text(
    "// Generated by scripts/spiral-portrait.py from public/kumma/portrait.jpg.\n"
    "// The photograph's tone along the spiral, 4 bits per sample.\n"
    f"export const portrait = {{\n  turns: {TURNS},\n  radius: {RADIUS:g},\n  step: {STEP:g},\n"
    f"  count: {len(tones)},\n  tones:\n    \"{data}\",\n}};\n",
    encoding="utf-8",
)
print(f"{len(tones)} samples -> {OUT.relative_to(ROOT)} ({OUT.stat().st_size // 1024} KB)")
